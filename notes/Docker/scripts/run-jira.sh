#!/bin/bash
# Запуск Jira с автоудалением контейнера и корректной остановкой

# 1. Проверяем наличие локального образа
if ! docker image inspect atlassian/jira-software:latest >/dev/null 2>&1; then
    echo "Ошибка: локальный образ atlassian/jira-software:latest не найден."
    echo "Выполните один раз: docker pull atlassian/jira-software:latest"
    exit 1
fi

# 2. Удаляем старый контейнер с таким именем (если остался от сбоев)
docker rm -f jira >/dev/null 2>&1

# 3. Запускаем Jira в фоне с автоудалением
#    -d        — в фоне
#    -p 2990:8080 — порт 2990 хоста -> порт 8080 контейнера
#    --rm      — удалить контейнер после остановки
docker run -d --rm --name jira \
  -p 2990:8080 \
  atlassian/jira-software:latest

# 4. Ждём пару секунд, чтобы контейнер создался
sleep 2

echo "Jira запускается. Это может занять 5-10 минут."
echo "Логи в реальном времени (нажмите Ctrl+C для остановки и удаления):"
echo "---------------------------------------------------------------"

# 5. Ловим Ctrl+C для корректной остановки Jira
#    Используем --time 60, чтобы дать Jira время на завершение (иначе возможна ошибка блокировки)
trap 'echo -e "\nОстанавливаем Jira (это может занять до минуты)..."; docker stop jira --time 60 >/dev/null 2>&1; exit 0' INT TERM

# 6. Показываем логи в реальном времени (это держит скрипт активным)
docker logs -f jira
