#!/bin/bash
# Запуск Apache (httpd) с автоматическим удалением контейнера при выходе

# 1. Проверяем, есть ли локальный образ httpd
if ! docker image inspect httpd:latest >/dev/null 2>&1; then
    echo "Ошибка: локальный образ httpd:latest не найден."
    echo "Выполните один раз: docker pull httpd:latest"
    exit 1
fi

# 2. На всякий случай удаляем старый контейнер с таким именем (если остался от сбоев)
docker rm -f my-apache >/dev/null 2>&1

# 3. Запускаем контейнер
#    -d        — в фоне (чтобы веб-сервер работал, пока мы не зайдём внутрь)
#    -p 8081:80 — порт 8081 хоста -> порт 80 контейнера
#    --rm      — автоматически удалить контейнер после его остановки
docker run -d --rm --name my-apache -p 8081:80 httpd:latest

# 4. Ждём пару секунд, чтобы сервер успел запуститься
sleep 2

echo "Apache запущен: http://localhost:8081"
echo "Чтобы войти в контейнер, выполните в другом терминале:"
echo "  docker exec -it my-apache bash"
echo "Чтобы остановить и удалить контейнер, нажмите Ctrl+C в этом терминале."

# 5. Ловим Ctrl+C, чтобы остановить контейнер (и он удалился благодаря --rm)
trap 'echo -e "\nОстанавливаем Apache..."; docker stop my-apache >/dev/null 2>&1; exit 0' INT TERM

# 6. Держим скрипт активным, пока пользователь не нажмёт Ctrl+C
#    (иначе скрипт сразу завершится, и контейнер в фоне останется работать)
while true; do
    sleep 1
done
